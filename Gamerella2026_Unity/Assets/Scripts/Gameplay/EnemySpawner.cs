using System;
using System.Collections.Generic;
using System.Linq;
using UnityEngine;
using Random = UnityEngine.Random;

using static EnemyFactory;
using static SpawnIntervalsConfigurationSO;

/// <summary>
/// Continually spawns enemies on the map
/// </summary>
public class EnemySpawner : MonoBehaviour
{
    [SerializeField]
    private EnemyConfigurationsSO _enemyConfigurations = null;
    
    [SerializeField]
    private EnemyFactory _enemyFactory = null;
    
    [SerializeField]
    private EnemyManager _enemyManager = null;

    [SerializeField]
    private Transform _enemiesTransform = null;
    
    [SerializeField]
    private SpawnIntervalsConfigurationSO _spawnIntervalsConfiguration = null;

    [SerializeField]
    private List<Transform> _enemySpawnPoints = null;

    public int SpawnIntervalNum { get; private set; }

    private const float AutoGeneratedIntervalTimeSeconds = 30;
    private const int AutoGeneratedIntervalNumAdditionalEnemies = 15;

    private static Dictionary<EnemyType, float> _cachedEnemySpawnProbabilites = new();
    private static readonly EnemyType[] EnemyTypes = (EnemyType[]) Enum.GetValues(typeof(EnemyType));
    
    private SpawnInterval CurrSpawnInterval;
    private List<SpawnInterval> _spawnIntervals;
    
    private int _currSpawnIntervalIndex;

    private float? _timeOfLastSpawn;

    private void Awake()
    {
        // Assume we provide at least one user interval
        _spawnIntervals = Instantiate(_spawnIntervalsConfiguration).SpawnIntervals;
        CurrSpawnInterval = _spawnIntervals[0];
    }

    private void Update()
    {
        if (ShouldUpdateCurrInterval(out SpawnInterval updatedSpawnInterval))
        {
            // Spawn anything remaining in the last (but still technically current) interval
            foreach (SpawnEnemyType spawnEnemyType in CurrSpawnInterval.SpawnEnemyTypes)
            {
                for (int i = spawnEnemyType.NumSpawned; i < spawnEnemyType.NumToSpawn; i++)
                {
                    SpawnEnemy(spawnEnemyType.EnemyType);
                }
            }

            _currSpawnIntervalIndex++;
            CurrSpawnInterval = updatedSpawnInterval;
            SpawnIntervalNum++;
        }

        // Spawn anything in the new interval
        int numSpawned = CurrSpawnInterval.TotalSpawned;
        int numShouldBeSpawned = Mathf.FloorToInt(CurrSpawnInterval.PctCompletion * CurrSpawnInterval.TotalToSpawn);
        
        for (int i = numSpawned; i < numShouldBeSpawned; i++)
        {
            Dictionary<EnemyType, float> enemyTypeSpawnProbabilites = GetRemainingSpawnEnemyTypeProbabilites(CurrSpawnInterval);
            float random = Random.value;

            float sumProbabilities = 0;
            EnemyType spawnEnemyWithType = default;
            
            foreach (EnemyType enemyType in EnemyTypes)
            {
                if (!enemyTypeSpawnProbabilites.TryGetValue(enemyType, out float spawnProbability))
                {
                    continue;
                }

                spawnEnemyWithType = enemyType;
                sumProbabilities += spawnProbability;
                
                if (sumProbabilities <= random)
                {
                    break;
                }
            }
            
            SpawnEnemy(spawnEnemyWithType);
            foreach (SpawnEnemyType intervalSpawnEnemyType in CurrSpawnInterval.SpawnEnemyTypes)
            {
                if (intervalSpawnEnemyType.EnemyType == spawnEnemyWithType)
                {
                    intervalSpawnEnemyType.NumSpawned++;
                    break;
                }
            }
        }
    }

    private void SpawnEnemy(EnemyType enemyType)
    {
        // Get the enemy's GameObject
        EnemyController enemy = _enemyFactory.FetchEnemyFromPool(enemyType);
        
        // Put it in the correct position
        Transform spawnPoint = _enemySpawnPoints[Random.Range(0, _enemySpawnPoints.Count)];
        enemy.transform.position = spawnPoint.position;
        enemy.transform.SetParent(_enemiesTransform);
        
        // Add tracking
        _enemyManager.RegisterEnemy(enemy);
        
        // Actual spawn
        enemy.SpawnWithConfiguration(_enemyConfigurations.EnemyConfigs[enemyType]);
    }

    public void CleanupEnemy(EnemyController enemy)
    {
        _enemyManager.UnregisterEnemy(enemy);
        _enemyFactory.ReturnEnemyToPool(enemy);
    }

    private bool ShouldUpdateCurrInterval(out SpawnInterval updatedSpawnInterval)
    {
        updatedSpawnInterval = null;
        
        if (Game.Instance.ElapsedTimeSeconds < CurrSpawnInterval.EndIntervalSecondsExclusive)
        {
            return false;
        }

        if (_currSpawnIntervalIndex + 1 < _spawnIntervals.Count)
        {
            updatedSpawnInterval = _spawnIntervals[_currSpawnIntervalIndex + 1];
            return true;
        }
        
        // Out of manually assigned intervals. Auto-generate the next interval, increasing the enemies
        Debug.LogWarning("Using auto-generated intervals");

        // Calculate what percent of each enemy type was spawned in this interval
        int spawnTotal = CurrSpawnInterval.SpawnEnemyTypes.Sum(s => s.NumToSpawn);

        // Add additional spawns for the next interval. Keep the same ratio of enemy types as the last interval
        int nextSpawnTotal = spawnTotal + AutoGeneratedIntervalNumAdditionalEnemies;
        List<SpawnEnemyType> nextIntervalSpawnEnemyTypes = new();
        Dictionary<EnemyType, float> currSpawnProbabilities = GetOverallSpawnEnemyTypeProbabilites(CurrSpawnInterval);
        
        foreach (SpawnEnemyType spawnEnemyType in CurrSpawnInterval.SpawnEnemyTypes)
        {
            EnemyType enemyType = spawnEnemyType.EnemyType;
            nextIntervalSpawnEnemyTypes.Add(new SpawnEnemyType(
                enemyType, 
                Mathf.CeilToInt(nextSpawnTotal * currSpawnProbabilities[enemyType])));
        }
        
        updatedSpawnInterval = new SpawnInterval(
            Game.Instance.ElapsedTimeSeconds,
            Game.Instance.ElapsedTimeSeconds + AutoGeneratedIntervalTimeSeconds,
            nextIntervalSpawnEnemyTypes);

        return true;
    }

    /// <summary>
    /// Returns the probability of each enemy type being spawned in the interval
    /// </summary>
    private static Dictionary<EnemyType, float> GetOverallSpawnEnemyTypeProbabilites(SpawnInterval spawnInterval)
    {
        _cachedEnemySpawnProbabilites.Clear();
        
        int totalOverallIntervalSpawns = spawnInterval.SpawnEnemyTypes.Sum(s => s.NumToSpawn);
        foreach (SpawnEnemyType spawnEnemyType in spawnInterval.SpawnEnemyTypes)
        {
            if (spawnEnemyType.NumToSpawn > 0)
            {
                EnemyType enemyType = spawnEnemyType.EnemyType;
                _cachedEnemySpawnProbabilites.Add(enemyType, spawnEnemyType.NumToSpawn / (float) totalOverallIntervalSpawns);   
            }
        }

        return _cachedEnemySpawnProbabilites;
    }
    
    /// <summary>
    /// Returns the probability of the next enemy type spawn in the running interval
    /// </summary>
    private static Dictionary<EnemyType, float> GetRemainingSpawnEnemyTypeProbabilites(SpawnInterval runningInterval)
    {
        _cachedEnemySpawnProbabilites.Clear();
        
        int totalRemainingIntervalSpawns = runningInterval.SpawnEnemyTypes.Sum(s => s.RemainingToSpawn);
        foreach (SpawnEnemyType spawnEnemyType in runningInterval.SpawnEnemyTypes)
        {
            if (spawnEnemyType.RemainingToSpawn > 0)
            {
                EnemyType enemyType = spawnEnemyType.EnemyType;
                _cachedEnemySpawnProbabilites.Add(enemyType, spawnEnemyType.RemainingToSpawn / (float) totalRemainingIntervalSpawns);   
            }
        }

        return _cachedEnemySpawnProbabilites;
    }
}